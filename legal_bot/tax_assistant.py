# V71: richer local-first screenshot interpretation. No external AI is used.
def _tax_normalize_digits(text):
    return str(text).translate(str.maketrans('۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩', '01234567890123456789'))


def _tax_screen_signals(text):
    """Extract only high-confidence labels/options from OCR text.

    This deliberately avoids interpreting arbitrary numbers as tax values. The
    result is a small set of labels the user can verify against the screenshot.
    """
    t=(text or '').replace('ي','ی').replace('ك','ک')
    signals=[]
    patterns=[
        ('درآمد/فروش', ('درآمد','فروش','فروش خالص','درآمد ناخالص')),
        ('هزینه/مخارج', ('هزینه','هزینه ها','هزینه‌ها','مخارج')),
        ('معافیت', ('معافیت','معاف')),
        ('مالیات', ('مالیات متعلقه','مالیات قابل پرداخت','مالیات','مانده مالیات')),
        ('نوع فعالیت', ('نوع فعالیت','شرح فعالیت','فعالیت اصلی')),
        ('وضعیت پرونده', ('وضعیت پرونده','پرونده مالیاتی','شماره پرونده')),
        ('ابلاغ/برگ تشخیص', ('برگ تشخیص','برگ قطعی','ابلاغ','تاریخ ابلاغ')),
        ('سامانه مؤدیان', ('سامانه مؤدیان','مودیان','صورتحساب الکترونیکی')),
        ('درخواست/اعتراض', ('اعتراض','درخواست تجدیدنظر','رسیدگی مجدد')),
    ]
    for label, keys in patterns:
        hits=[k for k in keys if k in t]
        if hits:
            signals.append((label,hits[0]))
    return signals


def _tax_option_hints(text):
    """Recognize common checkbox/radio words; never decide which one is right."""
    t=(text or '').replace('ي','ی').replace('ك','ک')
    options=[]
    for label, keys in [
        ('بله',('☑ بله','□ بله','بله')),
        ('خیر',('☑ خیر','□ خیر','خیر')),
        ('مشمول',('مشمول','مشمول مالیات')),
        ('معاف',('معاف','معافیت')),
        ('اصلی',('اصلی','فعالیت اصلی')),
        ('فرعی',('فرعی','فعالیت فرعی')),
    ]:
        if any(k in t for k in keys):
            options.append(label)
    return list(dict.fromkeys(options))


def build_tax_screen_guide(ocr_text, answers=None):
    """Create a local, conservative, user-friendly guide from OCR text."""
    text=(ocr_text or '').replace('ي','ی').replace('ك','ک').strip()
    answers=answers or {}
    if not text:
        return ('📸 متن قابل تشخیصی از تصویر پیدا نشد.\n\n'
                'لطفاً از همان صفحه یک عکس واضح‌تر بفرستید؛ ترجیحاً عنوان، گزینه‌ها و عددهای صفحه کامل دیده شوند.\n\n'
                '💡 اگر فقط یک قسمت برایت مبهم است، از همان قسمت عکس نزدیک‌تر بفرست.\n\n'
                '⚠️ برای تعیین گزینه قانونی قطعی، تصویر کامل صفحه و مقررات همان سال لازم است.')

    signals=_tax_screen_signals(text)
    options=_tax_option_hints(text)
    digits=_tax_normalize_digits(text)
    amounts=re.findall(r'(?<!\d)\d{1,3}(?:[,.]\d{3})+(?!\d)', digits)
    quality='بالا' if len(text)>=180 and len(signals)>=2 else ('متوسط' if len(text)>=80 or signals else 'پایین')

    lines=['📸 راهنمای همین صفحه','','🔎 چیزهایی که از تصویر با اطمینان نسبی تشخیص دادم:']
    if signals:
        for label, hit in signals[:8]:
            lines.append(f'• {label} ← عبارت «{hit}» دیده شد.')
    else:
        lines.append('• عنوان مشخص و آشنایی که بتوان با اطمینان توضیح داد پیدا نشد.')

    lines += ['',f'📊 کیفیت تشخیص متن: {quality}']
    if options:
        lines += ['☑️ واژه/گزینه‌های دیده‌شده: '+ '، '.join(options[:8]),
                  '⚠️ دیده‌شدن یک گزینه به معنی مناسب‌بودن آن برای شما نیست؛ انتخاب نهایی را بر اساس شرایط واقعی و مقررات انجام بده.']
    if amounts:
        lines += ['', '🔢 عددهای قابل تشخیص از تصویر:', '• '+ '، '.join(amounts[:6]),
                   '⚠️ این اعداد را عمداً به عنوان «درآمد» یا «مالیات» تفسیر نکردم؛ عنوان کنار هر عدد باید بررسی شود.']

    lines += ['', '🧭 الان چه کار کنی؟']
    if any(x[0]=='درآمد/فروش' for x in signals):
        lines.append('1) اول عنوان دقیق فیلد درآمد/فروش را با سال مالیاتی تطبیق بده.')
    if any(x[0]=='هزینه/مخارج' for x in signals):
        lines.append('2) اگر هزینه‌ای وارد می‌کنی، واقعی‌بودن و داشتن مدرک و شرایط قبول مالیاتی آن را بررسی کن.')
    if any(x[0]=='معافیت' for x in signals):
        lines.append('3) اگر گزینه معافیت می‌بینی، قبل از علامت‌زدن شرط قانونی آن را کنترل کن.')
    if any(x[0] in {'ابلاغ/برگ تشخیص','درخواست/اعتراض'} for x in signals):
        lines.append('4) اگر این صفحه مربوط به ابلاغ یا اعتراض است، تاریخ ابلاغ و نوع برگه را دقیق نگه دار؛ مهلت می‌تواند مهم باشد.')
    if not signals:
        lines.append('1) عکس نزدیک‌تر از بخش موردنظر بفرست تا عنوان فیلد و گزینه‌ها واضح‌تر خوانده شوند.')

    if answers.get('activity'):
        lines += ['',f'👤 سابقه گفت‌وگو: نوع فعالیت شما «{ACTIVITIES.get(answers.get("activity"), answers.get("activity"))}» ثبت شده است.']

    lines += ['', '📋 قاعده ساده:',
              'عنوان فیلد → معنی فیلد → اطلاعات واقعی خودت → بررسی شرط قانونی → سپس ثبت در سامانه.',
              '', '⚠️ LegalBot فرم رسمی را پر یا ارسال نمی‌کند و از روی OCR به‌تنهایی گزینه قانونی قطعی انتخاب نمی‌کند.',
              '💡 اگر یک گزینه مشخص برایت سؤال است، همان قسمت را جداگانه و واضح بفرست تا بررسی محلی دقیق‌تری انجام شود.']
    return '\n'.join(lines)

