def search_hint(role: str, topic: str) -> str:
    hints = {
        ("creditor", "claim"): "دادخواست مطالبه مهریه",
        ("creditor", "index"): "شاخص مهریه تعدیل",
        ("creditor", "exec"): "اجرائیه مهریه توقیف",
        ("creditor", "install"): "تقسیط مهریه توافق",
        ("debtor", "esar"): "دادخواست اعسار از پرداخت مهریه",
        ("debtor", "install"): "تقسیط محکوم به مهریه",
        ("debtor", "object"): "اعتراض به محاسبه مهریه",
        ("debtor", "lift"): "رفع ممنوع الخروجی مهریه",
    }
    return hints.get((role, topic), "مهریه اعسار")
