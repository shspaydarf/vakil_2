def role_keyboard_rows():
    return [
        [("👤 من مستأجرم", "ejare:role:tenant")],
        [("🏢 من موجرم", "ejare:role:landlord")],
        [("🏠 منوی اصلی", "home")],
    ]


def topic_keyboard_rows(role: str):
    topics = TENANT_TOPICS if role == "tenant" else LANDLORD_TOPICS
    rows = []
    for key, label in topics.items():
        rows.append([(label, f"ejare:topic:{role}:{key}")])
    rows.append([("↩️ تغییر نقش", "ejare"), ("🏠 منوی اصلی", "home")])
    return rows


