def list_templates():
    return [(key, meta["title"]) for key, meta in TEMPLATES.items()]


def get_template(key: str) -> str:
    meta = TEMPLATES.get(key)
    if not meta:
        raise KeyError(key)
    body = meta["body"].strip()
    return (
        body
        + "\n\n"
        + "─" * 24
        + "\n⚠️ قالب آماده و آموزشی است. جای خالی‌ها را با مشخصات واقعی پر کنید؛ "
        "قبل از ثبت/تقدیم توسط وکیل بازبینی شود. نتیجه پرونده تضمین نمی‌شود."
    )


