def build_shora_guide(answers: dict) -> str:
    topic = answers.get("topic", "other")
    amount = answers.get("amount", "unknown")
    docs = answers.get("docs", "no")

    topic_label = TOPICS.get(topic, TOPICS["other"])
    amount_label = AMOUNT_BANDS.get(amount, AMOUNT_BANDS["unknown"])
    docs_label = HAS_DOC.get(docs, HAS_DOC["no"])

    lines = [
        "⚖️ راهنمای شورای حل اختلاف و دادگاه صلح",
        "",
        f"🔹 موضوع: {topic_label}",
        f"🔹 حدود مبلغ/خواسته: {amount_label}",
        f"🔹 وضعیت مدارک: {docs_label}",
        "",
    ]

    lines += _competence_section(topic, amount)
    lines += _documents_section(topic, docs)
    lines += _steps_section()
    lines += _sana_section()
    lines += _warnings_section()

    lines += [
        "",
        "🔗 لینک‌های رسمی",
        "• عدل ایران: https://adliran.ir",
        "• ثبت‌نام ثنا: https://sana.adliran.ir",
        "• ابلاغ الکترونیک: https://eblagh.adliran.ir",
    ]

    return "\n".join(lines)
