            "• گزارش پلیس یا صورت‌جلسه (در صورت وجود)",
            "• فاکتور تعمیرات، برآورد خسارت یا نظریه کارشناسی",
            "• عکس یا فیلم از محل و میزان خسارت",
            "• مدارک بیمه (در صورت داشتن)",
