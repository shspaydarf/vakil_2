def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").replace("ي", "ی").replace("ك", "ک")).strip().casefold()


@lru_cache(maxsize=1)
def _corpus():
    def load(name, default):
        try:
            return json.loads((BASE / name).read_text(encoding="utf-8"))
        except Exception:
            return default
    return {
        "laws": load("laws.json", {}),
        "rulings": load("rulings.json", {}).get("rulings", []),
        "consultations": load("consultations.json", {}).get("consultations", []),
        "terms": load("important_terms.json", []),
    }


def _source_candidates(pack, limit=8):
    corpus = _corpus()
    laws = corpus["laws"]
    found = []
    for law_name in pack.get("laws", []):
        # Exact/normalized title match first; fallback to contains.
        for title, articles in laws.items():
            if _norm(title) == _norm(law_name) or _norm(law_name) in _norm(title) or _norm(title) in _norm(law_name):
                found.append({"type": "law", "title": title, "articles": len(articles) if isinstance(articles, list) else None})
                break
    return found[:limit]


def _related_records(records, terms, limit=4):
    terms_n = [_norm(x) for x in terms if x]
    scored = []
    for rec in records:
        hay = _norm(" ".join(str(rec.get(k, "")) for k in ("عنوان", "متن", "سؤال", "نظریه", "شماره", "موضوع")))
        hits = [t for t in terms_n if t and t in hay]
        if hits:
            scored.append((sum(len(x) for x in hits), len(hits), rec))
    scored.sort(key=lambda x: (x[0], x[1]), reverse=True)
    out = []
    for _, _, rec in scored[:limit]:
        if "شماره" in rec:
            out.append({"type": "ruling", "number": rec.get("شماره"), "date": rec.get("تاریخ"), "title": rec.get("عنوان", "")[:220]})
        else:
            out.append({"type": "consultation", "number": rec.get("شماره"), "date": rec.get("تاریخ"), "title": (rec.get("سؤال") or "")[:220]})
    return out


def _related_terms(text, limit=8):
    corpus = _corpus()
    t = _norm(text)
    scored = []
    for item in corpus["terms"]:
        phrase = item.get("phrase", "") if isinstance(item, dict) else ""
        p = _norm(phrase)
        if p and p in t:
            scored.append((len(p), item))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [x[1].get("phrase") for x in scored[:limit]]


def detect_packs(text: str, limit: int = 7):
    t = _norm(text)
    scored = []
    for key, pack in PACKS.items():
        hits = [s for s in pack["signals"] if _norm(s) in t]
        if not hits:
            continue
        score = sum(2 if len(h) >= 7 else 1 for h in hits)
        scored.append((score, len(hits), key, hits))
    scored.sort(reverse=True)
    return [{"key": k, "title": PACKS[k]["title"], "score": score, "signals": hits} for score, _, k, hits in scored[:limit]]


def build_pack_guidance(text: str):
    detected = detect_packs(text)
    corpus = _corpus()
    out = []
    for d in detected:
        p = PACKS[d["key"]]
        source_candidates = _source_candidates(p, limit=8)
        out.append({
            "key": d["key"], "title": p["title"], "score": d["score"], "signals": d["signals"][:10],
            "sources": [x["title"] for x in source_candidates],
            "source_candidates": source_candidates,
            "related_rulings": _related_records(corpus["rulings"], p.get("ruling_terms", [])),
            "related_consultations": _related_records(corpus["consultations"], p.get("consultation_terms", [])),
            "related_terms": _related_terms(text),
            "issues": p["issues"], "docs": p["docs"], "evidence": p.get("evidence", []),
            "questions": p["questions"], "actions": p["actions"], "red_flags": p["red_flags"],
        })
    return out
